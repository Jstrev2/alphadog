// Writes the SQL that loads one pilot area's OpenStreetMap hydrants, poles,
// lamp posts, dog parks and bag stations into public.osm_spots. The database
// uses them to award badges (Fire Dog, Tuff Stuff, Park Life) when a dog marks.
//
//   node scripts/osm-spots-sql.ts andersonville > supabase/migrations/<timestamp>_osm_spots_<area>.sql
//
// Run `npm run data:<area>` first. The output is derived from OpenStreetMap (ODbL).

import { readFileSync } from "node:fs";
import { AREAS } from "../src/lib/areas.ts";
import { FEATURE_CODE, type AreaData } from "../src/lib/feature-types.ts";

const areaId = process.argv[2];
if (!areaId) throw new Error("Usage: node scripts/osm-spots-sql.ts <area id>");
const data = JSON.parse(readFileSync(`public/data/areas/${areaId}.json`, "utf8")) as AreaData;

const KINDS: Record<number, string> = {
  [FEATURE_CODE.hydrant]: "hydrant",
  [FEATURE_CODE.post]: "post",
  [FEATURE_CODE.dog_park]: "dog_park",
  [FEATURE_CODE.waste_station]: "waste_station",
};
const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows = data.features
  .filter(([, , code]) => KINDS[code])
  .map(([lon, lat, code, name]) => `  (${quote(KINDS[code])}, ${lon}, ${lat}, ${name ? quote(name) : "null"})`);

const [w, s, e, n] = AREAS.find((a) => a.id === areaId)!.bbox;
console.log(`-- OpenStreetMap spots for the ${data.name} pilot, from public/data/areas/${areaId}.json.
-- Generated by scripts/osm-spots-sql.ts. Data © OpenStreetMap contributors (ODbL).
-- Safe to run again: it replaces the spots inside the area first.

delete from public.osm_spots where lon between ${w} and ${e} and lat between ${s} and ${n};

insert into public.osm_spots (kind, lon, lat, name) values
${rows.join(",\n")};`);
